"""Resize an animated GIF to fit the ESP32 screen and emit it as a C header.

Usage (from the esp32/ folder):
    python tools/gif2header.py ../gifs/mai-san-wave.gif src/gifs/wave.h gif_wave

The AnimatedGIF library draws at the GIF's native size, so frames are scaled to fit
GIF_MAX_W x GIF_MAX_H (the left side of the 320x240 landscape screen; the right side
shows the reply text). Frames are flattened onto a solid background so the result
has no transparency for the firmware to handle.
"""
import io
import sys
from pathlib import Path

from PIL import Image, ImageSequence

GIF_MAX_W = 200
GIF_MAX_H = 240
BACKGROUND = (0, 0, 0)


def convert(src: Path) -> bytes:
    im = Image.open(src)
    scale = min(GIF_MAX_W / im.width, GIF_MAX_H / im.height, 1.0)
    size = (max(1, round(im.width * scale)), max(1, round(im.height * scale)))

    frames, durations = [], []
    for frame in ImageSequence.Iterator(im):
        rgba = frame.convert("RGBA")  # Pillow applies GIF disposal while iterating
        flat = Image.new("RGB", rgba.size, BACKGROUND)
        flat.paste(rgba, mask=rgba.getchannel("A"))
        flat = flat.resize(size, Image.LANCZOS)
        frames.append(flat.quantize(colors=256, method=Image.Quantize.MEDIANCUT))
        durations.append(frame.info.get("duration", 100))

    out = io.BytesIO()
    frames[0].save(
        out,
        format="GIF",
        save_all=True,
        append_images=frames[1:],
        duration=durations,
        loop=0,
        disposal=1,
        optimize=False,
    )
    print(f"{src.name}: {im.width}x{im.height} -> {size[0]}x{size[1]}, "
          f"{len(frames)} frames, {out.tell()} bytes")
    return out.getvalue()


def write_header(data: bytes, dest: Path, name: str, src: Path) -> None:
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n  ".join(lines)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        f"// Generated by tools/gif2header.py from {src.name}. Do not edit by hand.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f"const uint8_t {name}[] PROGMEM = {{\n  {body}\n}};\n"
        f"const size_t {name}_len = {len(data)};\n",
        encoding="ascii",
    )


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, dest, name = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    write_header(convert(src), dest, name, src)
